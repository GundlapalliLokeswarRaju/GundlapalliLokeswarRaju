"""Rebuild the Featured Projects section of README.md from the owner's public GitHub repos.

Ranking: repos with the "featured" topic first, then most stars, then most recently pushed.
Forks, archived repos, private repos and the profile repo itself are skipped.
Uses only the Python standard library.
"""
import json
import os
import re
import sys
import urllib.request

USER = os.environ.get("GH_USER", "GundlapalliLokeswarRaju")
TOKEN = os.environ.get("GITHUB_TOKEN", "")
README = os.environ.get("README_PATH", "README.md")
CARDS = int(os.environ.get("FEATURED_COUNT", "6"))
START = "<!--START_SECTION:projects-->"
END = "<!--END_SECTION:projects-->"
THEME = "hide_border=true&bg_color=0a1628&title_color=ff9a3c&text_color=dbe6f5&icon_color=ff7a3d"


def fetch_repos():
    repos, page = [], 1
    while True:
        url = f"https://api.github.com/users/{USER}/repos?per_page=100&page={page}&type=owner&sort=pushed"
        req = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json"})
        if TOKEN:
            req.add_header("Authorization", f"Bearer {TOKEN}")
        with urllib.request.urlopen(req, timeout=30) as resp:
            batch = json.load(resp)
        repos.extend(batch)
        if len(batch) < 100:
            return repos
        page += 1


def pick(repos):
    keep = [
        r for r in repos
        if not r.get("fork") and not r.get("archived") and not r.get("private")
        and r["name"].lower() != USER.lower()
    ]
    keep.sort(key=lambda r: r.get("pushed_at") or "", reverse=True)
    keep.sort(key=lambda r: r.get("stargazers_count", 0), reverse=True)
    keep.sort(key=lambda r: "featured" in (r.get("topics") or []), reverse=True)
    return keep


def clean(text):
    return (text or "").replace("|", "/").replace("\n", " ").strip()


def render(repos):
    ranked = pick(repos)
    if not ranked:
        return "_No public repositories yet._"
    lines = ['<div align="center">', ""]
    for r in ranked[:CARDS]:
        name = r["name"]
        lines.append(
            f'<a href="{r["html_url"]}"><img src="https://github-readme-stats.vercel.app/api/pin/'
            f'?username={USER}&repo={name}&{THEME}" alt="{name}" /></a>'
        )
    lines += ["", "</div>", ""]
    lines += [
        f"<details>",
        f"<summary><b>All {len(ranked)} repositories</b> (click to expand)</summary>",
        "",
        "| Project | Description | Language | Stars |",
        "|:---|:---|:---|---:|",
    ]
    for r in ranked:
        desc = clean(r.get("description")) or "-"
        lang = r.get("language") or "-"
        lines.append(f"| [{r['name']}]({r['html_url']}) | {desc} | {lang} | {r.get('stargazers_count', 0)} |")
    lines += ["", "</details>"]
    return "\n".join(lines)


def replace_section(text, block):
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        sys.exit(f"Markers {START} / {END} not found in {README}")
    new = f"{START}\n<!-- Auto-generated by scripts/update_projects.py. Do not edit between these markers. -->\n\n{block}\n\n{END}"
    return pattern.sub(lambda _m: new, text, count=1)


def main():
    with open(README, encoding="utf-8") as f:
        old = f.read()
    new = replace_section(old, render(fetch_repos()))
    if new != old:
        with open(README, "w", encoding="utf-8") as f:
            f.write(new)
        print("README updated")
    else:
        print("No changes")


if __name__ == "__main__":
    main()
